# -*- coding: utf-8 -*-
"""Текст выступления (~8 минут) на 2 рассказчиков по презентации 'Антивирус_вариант_7_KES.pptx'.

Формат как в Bibliv_Mikhailich_2_text_for_two_speakers.docx:
заголовки 'Рассказчик N' и 'Слайд N. ...' жирным, реплики обычным текстом 12 pt.
"""
import os

from docx import Document
from docx.shared import Pt

BASE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(BASE, "Five", "Law", "Антивирус_вариант_7_KES_текст_2_рассказчика.docx")


def add_heading(doc, text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.bold = True
    r.font.size = Pt(12)


def add_line(doc, text):
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.font.size = Pt(12)
    return p


def build():
    doc = Document()
    style = doc.styles["Normal"]
    style.font.name = "Times New Roman"
    style.font.size = Pt(12)

    # ---------- РАССКАЗЧИК 1 ----------
    add_heading(doc, "Рассказчик 1")
    add_heading(doc, "Слайд 1. Титульный — постановка работы")
    add_line(doc,
             "Здравствуйте! Мы представляем практическую работу по теме государственных реестров "
             "Минцифры, Роскомнадзора и ФСТЭК. Наш вариант — седьмой: нужно подобрать антивирусное "
             "средство для организации, у которой нет сведений, содержащих государственную тайну, "
             "которая работает в финансовой сфере и испытывает большую нагрузку. В качестве решения "
             "мы предлагаем Kaspersky Endpoint Security — продукт «Лаборатории Касперского». "
             "В работе мы последовательно проверим это решение по реестру российского программного "
             "обеспечения, реестру сертифицированных средств защиты информации и по функциональным "
             "характеристикам. Цель — не просто назвать продукт, а доказать, что он действительно "
             "подходит под заданные условия.")
    add_heading(doc, "Слайд 2. Постановка задачи")
    add_line(doc,
             "Сначала зафиксируем исходные условия. Особенности организации: государственной тайны "
             "нет, сфера — финансовая, нагрузка — большая. Значит, нам нужно решение из реестра "
             "российского ПО и одновременно сертифицированное средство защиты информации ФСТЭК, "
             "с учётом срока действия сертификата. По заданию требуется подобрать ещё лицензиата на "
             "разработку и производство СЗИ, орган по аттестации объектов информатизации в регионе, "
             "а также аккредитованную испытательную лабораторию ФСТЭК. Отдельно подчеркну: "
             "поскольку государственной тайны в организации нет, класс защищённости по гостайне "
             "уточнять не нужно — это прямо оговорено в задании. Итог работы — обоснование выбора "
             "и презентация на пять–восемь минут.")
    add_heading(doc, "Слайд 3. Особенности применения и требования")
    add_line(doc,
             "Разберём, что означают эти особенности на практике. Отсутствие гостайны снимает "
             "необходимость в классе защищённости по государственной тайне — достаточно сертификации "
             "ФСТЭК для систем персональных данных и государственных информационных систем. "
             "Финансовая сфера добавляет требования Центрального банка, стандарт ГОСТ Р 57580, "
             "а также 152-ФЗ о персональных данных — антивирусная защита здесь обязательна. "
             "Большая нагрузка требует производительности, централизованного управления и тонких "
             "политик с исключениями для транзакционных систем и СУБД. Проще говоря, решение должно "
             "одновременно быть легитимным с точки зрения регуляторов, производительным и "
             "управляемым. Именно по этим трём осям мы и будем проверять наш вариант.")
    add_heading(doc, "Слайд 4. Проверка по государственным реестрам")
    add_line(doc,
             "Теперь — самое главное для этой работы: проверка по реестрам. По реестру российского "
             "ПО мы находим продукт «Лаборатории Касперского» в позиции, относящейся к средствам "
             "защиты информации. По реестру сертифицированных СЗИ ФСТЭК у Kaspersky Endpoint "
             "Security есть сертифицированная сборка: это уровень доверия и защита от "
             "недекларированных возможностей. Отдельно проверяем срок действия сертификата — его "
             "номер и дату нужно указать на момент закупки. Выписки из реестров и номер сертификата "
             "мы прикладываем скриншотами. Важный момент: в реестр российского ПО включены "
             "конкретные наименования и редакции, поэтому при закупке нужно брать именно ту позицию, "
             "которая в реестре, иначе не сработает ограничение на иностранное программное "
             "обеспечение. Таким образом, по всем формальным критериям решение уже подходит. "
             "Передаю слово коллеге.")

    # ---------- РАССКАЗЧИК 2 ----------
    add_heading(doc, "Рассказчик 2")
    add_heading(doc, "Слайд 5. Сравнение возможных вариантов")
    add_line(doc,
             "Спасибо. Мы сравнили несколько антивирусных средств по двум ключевым критериям: "
             "наличие в реестре российского ПО и действующий сертификат ФСТЭК. Kaspersky Endpoint "
             "Security проходит по обоим пунктам — есть позиция в реестре и сертифицированная сборка, "
             "поэтому он выбран. Dr.Web для бизнеса тоже есть в реестре и сертифицирован — это "
             "рабочая альтернатива. Средства вроде «Соболя» и продуктов VipNet в реестре и "
             "сертифицированы, но это не антивирусы, они решают другие задачи. А зарубежные "
             "антивирусы без записи в реестре нам не подходят по требованиям закупки. "
             "Критерии здесь простые и жёсткие: наличие в реестре российского ПО, действующий "
             "сертификат ФСТЭК и способность работать при большой нагрузке. По совокупности именно "
             "Kaspersky Endpoint Security даёт наилучший результат.")
    add_heading(doc, "Слайд 6. Обоснование выбора: Kaspersky Endpoint Security")
    add_line(doc,
             "Почему именно Kaspersky Endpoint Security. Первое — соответствие реестрам: продукт есть "
             "в реестре российского ПО, а сертифицированная сборка — в реестре СЗИ ФСТЭК. "
             "Второе — регуляторные требования: решение закрывает 152-ФЗ, требования Центрального "
             "банка и ГОСТ Р 57580, то есть полностью соответствует финансовой сфере. Третье — "
             "большая нагрузка: продукт масштабируется через Kaspersky Security Center, а тонкие "
             "политики и исключения позволяют не мешать работе транзакционных систем. Именно "
             "сочетание всех трёх факторов делает выбор обоснованным. Отмечу также, что "
             "сертифицированная сборка — это не отдельный продукт, а именно та редакция, которую мы "
             "и планируем закупать; при защите важно, чтобы номер сертификата относился к ней "
             "и был действителен на дату закупки.")
    add_heading(doc, "Слайд 7. Состав решения и внедрение")
    add_line(doc,
             "Теперь о том, как это выглядит в составе решения. Ядро — сам Kaspersky Endpoint "
             "Security: защита рабочих станций и серверов, файлов, веб-трафика, почты и "
             "поведенческий анализ. Управление централизуется через Kaspersky Security Center: это "
             "единые политики, отчёты и масштабирование на тысячи узлов. Для серверных и "
             "виртуальных сред используем KES для Linux и Kaspersky Security for Virtualization — "
             "это снижает нагрузку на инфраструктуру. Внедрение начинаем с исключений для СУБД и "
             "транзакционных систем, затем пилот на одном сегменте и поэтапное развёртывание. "
             "Такой подход позволяет не «уронить» критичные системы в момент установки и проверить "
             "решение на реальной нагрузке, прежде чем тиражировать его на всю организацию.")
    add_heading(doc, "Слайд 8. Источники и выводы")
    add_line(doc,
             "При подготовке мы опирались на реестр российского ПО на портале reestr.digital.gov.ru, "
             "реестр сертифицированных СЗИ на сайте ФСТЭК, реестр лицензиатов ФСТЭК, перечни органов "
             "по аттестации и аккредитованных лабораторий, а также официальную документацию "
             "«Лаборатории Касперского». Вывод: Kaspersky Endpoint Security — обоснованный выбор. "
             "Он есть в реестре российского ПО, сертифицирован ФСТЭК и подходит для организации "
             "финансовой сферы с большой нагрузкой. Отдельно напомню, что в реальном проекте нужно "
             "приложить актуальные выписки из реестров, указать действующий номер сертификата, "
             "а также определить лицензиата, орган по аттестации и испытательную лабораторию в "
             "своём регионе. Это и будет полным обоснованием выбора. Спасибо за внимание, "
             "готовы ответить на вопросы.")

    doc.save(OUT)
    words = sum(len(p.text.split()) for p in doc.paragraphs)
    print("Сохранено:", OUT)
    print("Слов:", words, "≈ минут:", round(words / 130, 1))


if __name__ == "__main__":
    build()

